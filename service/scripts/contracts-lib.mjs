/**
 * Tool-contract generation shared by `pnpm contracts:update` and `test/contract-drift.test.ts`.
 *
 * The finalized tool registry (`ALL_TOOL_SPECS`) is the single authority. Every artifact that used
 * to restate it by hand is generated from it here:
 *
 * - `capabilities/union-manifest.json` canonical rows;
 * - `packages/mcp/test/plugin-contract.json`, the recorded plugin argument surface;
 * - The tool-count blocks in `README.md` and `packages/mcp/README.md`.
 *
 * Provenance that cannot be derived is read, never invented: upstream rows keep their recorded
 * source contracts, and service-local tools must be declared in `SERVICE_LOCAL_TOOLS` below. A
 * registry tool that fits no class stops generation instead of receiving a fabricated row.
 *
 * Plain Node needs `register-source.mjs` and `--experimental-transform-types` before importing this
 * module; `scripts/update-contracts.mjs` does both. Vitest transforms the TypeScript itself.
 */
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { format } from 'oxfmt';

import { ALL_TOOL_SPECS } from '../packages/mcp/src/tools/registry.ts';
import { SERVER_ONLY_TOOLS } from '../packages/mcp/src/tools/runtime-registry.ts';
import { derivePluginContract, diffContracts } from '../packages/mcp/test/plugin-contract.ts';
import { schemaContractJson } from '../packages/shared/src/capability-manifest.ts';
import { PORTAL_TOOL_NAMES } from '../packages/shared/src/portal.ts';
import { MIN_PLUGIN_VERSION } from '../packages/shared/src/version.ts';

export const SERVICE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const UPDATE_COMMAND = 'pnpm contracts:update';

/** Source label of contracts this service defines itself (portal and service-local rows). */
export const SERVICE_SOURCE = 'super-figma-pipeline';

/**
 * Registry tools this service implements natively. They have no upstream source contract and are
 * not part of the portal contract, so each becomes a service-native manifest row whose only source
 * contract is the service's own input schema. Adding a tool here is a deliberate classification
 * step: generation refuses any registry tool that is not classified.
 */

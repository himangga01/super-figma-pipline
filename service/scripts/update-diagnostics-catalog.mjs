import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

import { format } from 'oxfmt';

import './register-source.mjs';

const root = resolve(import.meta.dirname, '..');
const target = join(root, 'packages/mcp/src/diagnostics-catalog.ts');
const codes = new Set([
  'ERR_INVALID_URL',
  'ECONNRESET',
  'ECONNREFUSED',
  'ENOENT',
  'ENOTDIR',
  'EACCES',
  'EPERM',
  'EPIPE',
  'ETIMEDOUT',
  'ENOSPC',
  'EMFILE',
  'ABORT_ERR',
  'EADDRINUSE',
  'EADDRNOTAVAIL',
  'EBUSY',
  'EEXIST',
  'ELOOP',
  'ENETDOWN',
  'ENETUNREACH',
  'ENOMEM',
  'ENOTEMPTY',
  'EROFS',
  'ENAMETOOLONG',
  'ENFILE',
  'EIO',
  'EBADF',
  'EINVAL',
  'ENOSYS',
  'ECONNABORTED',
  'EHOSTUNREACH',
]);
const modules = new Set();
const labels = new Set([
  'queued',
  'running',
  'awaiting-confirmation',
  'awaiting-approval',
  'succeeded',
  'failed',
  'cancelled',
  'unknown',
  'responded',
  'disconnected',
]);
async function collect(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  await Promise.all(
    entries.map(async entry => {
      const path = join(directory, entry.name);
      if (entry.isSymbolicLink()) throw Error('DIAGNOSTICS_CATALOG_SOURCE_LINK');
      if (entry.isDirectory()) {
        if (['test', 'tests', 'fixtures', 'node_modules', '.cache'].includes(entry.name)) return;
        return collect(path);
      }
      if (
        !entry.isFile() ||
        !entry.name.endsWith('.ts') ||
        path === target ||
        /(?:^|[.-])(?:test|spec|fixture)(?:[.-]|$)/u.test(entry.name)
      )
        return;
      modules.add(entry.name);
      const source = await readFile(path, 'utf8');
      // Error-code-shaped source labels, rather than arbitrary uppercase enum/body values.
      for (const match of source.matchAll(/['"]([A-Z][A-Z0-9]*_[A-Z0-9_]{1,126})['"]/gu))
        if (match[1]) codes.add(match[1]);
      for (const match of source.matchAll(
        /(?:\.record|diagnose|diagnosticEvent)\(\s*['"]([a-z][a-z0-9.-]{0,63})['"]/gu,
      ))
        if (match[1]) labels.add(match[1]);
      if (path.includes(join('mcp', 'src', 'control'))) {
        for (const match of source.matchAll(/\bid:\s*['"]([a-z][a-z0-9_.-]{0,127})['"]/gu))
          if (match[1]) labels.add(match[1]);
      }
    }),
  );
}
const packages = await readdir(join(root, 'packages'), { withFileTypes: true });
await Promise.all(
  packages
    .filter(entry => entry.isDirectory())
    .map(entry => collect(join(root, 'packages', entry.name, 'src'))),
);

// Read the actual registered inventories without executing any feature or opening a connection.
const featureModule = new URL('../packages/cli/src/service-functions.ts', import.meta.url).href;
const toolModule = new URL('../packages/cli/src/service-tool-catalog.ts', import.meta.url).href;
const activityModule = new URL('../packages/portal/src/contract.ts', import.meta.url).href;
const { serviceFeatures } = await import(featureModule);
const { serviceTools } = await import(toolModule);
const { ActivityTypeSchema } = await import(activityModule);
for (const row of [...serviceFeatures(), ...serviceTools()]) {
  if (!row || typeof row.name !== 'string' || !/^[a-z][a-z0-9_.-]{0,127}$/u.test(row.name))
    throw Error('DIAGNOSTICS_CATALOG_INVENTORY_INVALID');
  labels.add(row.name);
}
for (const label of ActivityTypeSchema.options) labels.add(label);
const text =
  '// Generated by scripts/update-diagnostics-catalog.mjs from production error/event/route/module labels and registered public inventories.\n' +
  `export const diagnosticErrorCodes = new Set(${JSON.stringify([...codes].toSorted())});\n` +
  `export const diagnosticStackModules = new Set(${JSON.stringify([...modules].toSorted())});\n` +
  `export const diagnosticLabels = new Set(${JSON.stringify([...labels].toSorted())});\n`;
const output = await format(target, text, {
  printWidth: 100,
  tabWidth: 2,
  singleQuote: true,
  endOfLine: 'lf',
  insertFinalNewline: true,
});
if (output.errors.length > 0) throw Error('DIAGNOSTICS_CATALOG_FORMAT_INVALID');
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== output.code) throw Error('DIAGNOSTICS_CATALOG_STALE');
  process.stdout.write('Diagnostics catalog matches source and public inventory\n');
} else {
  await writeFile(target, output.code);
  process.stdout.write(
    `Updated diagnostics catalog (${codes.size} codes, ${modules.size} modules, ${labels.size} labels)\n`,
  );
}

import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {randomUUID,createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {declareTestScope} from '../scripts/declare-test-scope.mjs';
import {resolvePnpmEntry} from '../scripts/package-manager-entry.mjs';
import {sourceFingerprint} from '../scripts/source-fingerprint.mjs';
import {testSkipCensus} from '../scripts/test-skip-census.mjs';
const root=resolve('.');
const source=JSON.parse(await readFile('artifacts/source-checks/current.json','utf8'));
if(source.status!=='succeeded'||source.sourceHash!==await sourceFingerprint(root))throw Error('Complete current source gates must pass first');
const id=randomUUID(),folder=resolve('artifacts/focused-checks',id);
await mkdir(folder,{recursive:true});
const scope=await declareTestScope({serviceRoot:root,file:'test/artifact-contents.test.ts',runId:id});
const scopePath=resolve(folder,'test-scope.json'),reportPath=resolve(folder,'vitest-report.json'),logPath=resolve(folder,'test.txt');
await writeFile(scopePath,JSON.stringify(scope,null,2)+'\n');
const execute=promisify(execFile),pnpm=resolvePnpmEntry();
const {stdout,stderr}=await execute(process.execPath,[pnpm,'exec','vitest','run','test/artifact-contents.test.ts'],{cwd:root,windowsHide:true,timeout:300000,maxBuffer:16777216,env:{...process.env,SFP_VITEST_JSON_REPORT:reportPath,PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD:'1'}});
await writeFile(logPath,stdout+'\n'+stderr);
const adjudication=await execute(process.execPath,['scripts/check-test-report.mjs',reportPath,'--log',logPath,'--scope',scopePath],{cwd:root,windowsHide:true,timeout:30000,maxBuffer:1048576,env:process.env});
await writeFile(resolve(folder,'adjudication.txt'),adjudication.stdout+'\n'+adjudication.stderr);
const report=JSON.parse(await readFile(reportPath,'utf8'));
const census=testSkipCensus(report,{serviceRoot:root,allowed:new Set(),forbidSkips:true,scope});
if(census.blockedSuites.length||source.sourceHash!==await sourceFingerprint(root))throw Error('Artifact scope or source changed');
const sha256=async path=>createHash('sha256').update(await readFile(path)).digest('hex');
const result={recordedAt:new Date().toISOString(),runId:id,sourceHash:source.sourceHash,sourceAttempt:source.attemptId,status:'passed',tests:report.numTotalTests,passed:report.numPassedTests,failed:report.numFailedTests,skipped:report.numPendingTests,scopeHash:await sha256(scopePath),reportHash:await sha256(reportPath),logHash:await sha256(logPath),folder};
await writeFile(resolve(folder,'report.json'),JSON.stringify(result,null,2)+'\n');
const docs=process.argv[2]??'../../../docs/testing/2026-10-03-cdd-generation';
await copyFile(resolve(folder,'report.json'),`${docs}/artifact-contents-checkpoint.json`);
await copyFile(reportPath,`${docs}/artifact-contents-tests.json`);
await copyFile(scopePath,`${docs}/artifact-contents-scope.json`);
console.log(JSON.stringify(result));
